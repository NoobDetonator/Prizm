/**
 * Writes a look preset into DOM controls.
 * @param {Record<string, HTMLElement>} ui
 * @param {string} key
 * @returns {boolean}
 */
export function applyLookPreset(ui, key) {
  const look = LOOK_PRESETS[key]
  if (!look) return false

  for (const [valueKey, uiKey] of Object.entries(LOOK_UI_KEYS)) {
    const el = ui[uiKey]
    const value = look.values[valueKey]
    if (!el || value === undefined) continue
    el.value = String(value)
  }

  if (ui.lookNote) ui.lookNote.textContent = look.note
  // Optional: look can force an environment plate
  if (look.values.envSource && ui.envSource) {
    ui.envSource.value = look.values.envSource
  }
  return true
}
